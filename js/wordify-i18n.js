function applyWordifyTranslations() {
    if (!window.i18n) return;
    const lang = i18n.getLang();
    const t = wordifyTranslations[lang] || wordifyTranslations.tr;

    const contentArea = document.getElementById('wordifyContentContainer');
    if (contentArea) {
        contentArea.innerHTML = t.contentHtml;
        document.title = t.appTitle;
        const h1 = document.querySelector('article h1');
        if (h1) h1.textContent = t.appTitle;
    }

    const backLink = document.querySelector('.back-link');
    if (backLink) backLink.textContent = t.backLink;

    if (typeof initializeTOC === 'function') {
        const tocSidebar = document.querySelector('.toc-sidebar');
        if (tocSidebar) {
            const existingBtn = tocSidebar.querySelector('.download-btn-sidebar');
            tocSidebar.innerHTML = '';
            if (existingBtn) {
                if (lang === 'en') {
                    existingBtn.querySelector('span:last-child').textContent = 'Download Wordify';
                } else {
                    existingBtn.querySelector('span:last-child').textContent = "Wordify'ı İndir";
                }
                tocSidebar.appendChild(existingBtn);
            }
        }
        initializeTOC();
    }
}

window.addEventListener('langChanged', applyWordifyTranslations);

document.addEventListener('DOMContentLoaded', () => {
    const checkI18n = setInterval(() => {
        if (window.i18n && window.i18n.translations) {
            clearInterval(checkI18n);
            applyWordifyTranslations();
        }
    }, 50);
    setTimeout(() => {
        clearInterval(checkI18n);
        applyWordifyTranslations();
    }, 1000);
});
